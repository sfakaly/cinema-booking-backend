CREATE TABLE cinema (
    id INT GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR(120) NOT NULL,
    address VARCHAR(255) NOT NULL,

    CONSTRAINT pk_cinema PRIMARY KEY (id),
    CONSTRAINT uq_cinema_name_address UNIQUE (name, address)
);


CREATE TABLE hall_type (
    id INT GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR(120) NOT NULL,
    minimum_interval_seconds INT NOT NULL,

    CONSTRAINT pk_hall_type PRIMARY KEY (id),
    CONSTRAINT uq_hall_type_name UNIQUE (name),
    CONSTRAINT chk_hall_type_minimum_interval_seconds CHECK (minimum_interval_seconds >= 0)
);


CREATE TABLE seat_type (
    id INT GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR(120) NOT NULL,
    surcharge NUMERIC(12, 2) NOT NULL,

    CONSTRAINT pk_seat_type PRIMARY KEY (id),
    CONSTRAINT uq_seat_type_name UNIQUE (name),
    CONSTRAINT chk_seat_type_surcharge CHECK (surcharge >= 0)
);


CREATE TABLE tariff (
    id INT GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR(120) NOT NULL,
    discount_percent SMALLINT NOT NULL,

    CONSTRAINT pk_tariff PRIMARY KEY (id),
    CONSTRAINT uq_tariff_name UNIQUE (name),
    CONSTRAINT chk_tariff_discount_percent CHECK (discount_percent >= 0 AND discount_percent <= 100)
);


CREATE TABLE movie (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    title VARCHAR(255) NOT NULL,
    description TEXT,
    age_rating VARCHAR(25) NOT NULL,
    duration_seconds INT NOT NULL,

    CONSTRAINT pk_movie PRIMARY KEY (id),
    CONSTRAINT chk_movie_duration_seconds CHECK (duration_seconds > 0),
    CONSTRAINT chk_movie_age_rating CHECK (age_rating IN ('ANY', 'SIX_PLUS', 'TWELVE_PLUS', 'SIXTEEN_PLUS', 'EIGHTEEN_PLUS'))
);


CREATE TABLE app_user (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR(255) NOT NULL,
    email VARCHAR(254) NOT NULL,
    phone_number VARCHAR(20) NOT NULL,
    role VARCHAR(20) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,

    CONSTRAINT pk_app_user PRIMARY KEY (id),
    CONSTRAINT uq_app_user_email UNIQUE (email),
    CONSTRAINT uq_app_user_phone_number UNIQUE (phone_number),
    CONSTRAINT chk_app_user_role CHECK (role IN ('USER', 'ADMIN'))
);


CREATE TABLE hall (
    id INT GENERATED BY DEFAULT AS IDENTITY,
    hall_type_id INT NOT NULL,
    cinema_id INT NOT NULL,
    name VARCHAR(120) NOT NULL,

    CONSTRAINT pk_hall PRIMARY KEY (id),
    CONSTRAINT uq_hall_cinema_name UNIQUE (cinema_id, name),
    CONSTRAINT fk_hall_hall_type FOREIGN KEY (hall_type_id) REFERENCES hall_type (id) ON DELETE RESTRICT,
    CONSTRAINT fk_hall_cinema FOREIGN KEY (cinema_id) REFERENCES cinema(id) ON DELETE RESTRICT
);


CREATE TABLE screening (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    hall_id INT NOT NULL,
    movie_id BIGINT NOT NULL,
    advertising_start_time TIMESTAMPTZ NOT NULL,
    advertising_duration_seconds INT NOT NULL DEFAULT 0,
    price NUMERIC(12, 2) NOT NULL,

    CONSTRAINT pk_screening PRIMARY KEY (id),
    CONSTRAINT fk_screening_hall FOREIGN KEY (hall_id) REFERENCES hall (id) ON DELETE RESTRICT,
    CONSTRAINT fk_screening_movie FOREIGN KEY (movie_id) REFERENCES movie (id) ON DELETE RESTRICT,
    CONSTRAINT chk_screening_advertising_duration_seconds CHECK (advertising_duration_seconds >= 0),
    CONSTRAINT chk_screening_price CHECK (price >= 0)
);


CREATE TABLE seat (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    seat_type_id INT NOT NULL,
    hall_id INT NOT NULL,
    row_number INT NOT NULL,
    seat_number INT NOT NULL,

    CONSTRAINT pk_seat PRIMARY KEY (id),
    CONSTRAINT uq_seat_hall_row_number_seat_number UNIQUE (hall_id, row_number, seat_number),
    CONSTRAINT fk_seat_seat_type FOREIGN KEY (seat_type_id) REFERENCES seat_type (id) ON DELETE RESTRICT,
    CONSTRAINT fk_seat_hall FOREIGN KEY (hall_id) REFERENCES hall (id) ON DELETE RESTRICT,
    CONSTRAINT chk_seat_row_number CHECK (row_number > 0),
    CONSTRAINT chk_seat_seat_number CHECK (seat_number > 0)
);


CREATE TABLE booking (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    screening_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    status VARCHAR(30) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    total_price NUMERIC(12, 2) NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,

    CONSTRAINT pk_booking PRIMARY KEY (id),
    CONSTRAINT fk_booking_screening FOREIGN KEY (screening_id) REFERENCES screening (id) ON DELETE RESTRICT,
    CONSTRAINT fk_booking_user FOREIGN KEY (user_id) REFERENCES app_user (id) ON DELETE RESTRICT,
    CONSTRAINT chk_booking_total_price CHECK (total_price >= 0),
    CONSTRAINT chk_booking_dates_chronology CHECK (expires_at > created_at),
    CONSTRAINT chk_booking_status CHECK (status IN ('PENDING_PAYMENT', 'CONFIRMED', 'CANCELLED', 'EXPIRED', 'RETURNED'))
);


CREATE TABLE screening_seat (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    seat_id BIGINT NOT NULL,
    screening_id BIGINT NOT NULL,
    current_booking_id BIGINT,
    status VARCHAR(30) NOT NULL,

    CONSTRAINT pk_screening_seat PRIMARY KEY (id),
    CONSTRAINT uq_screening_seat_screening_seat UNIQUE (screening_id, seat_id),
    CONSTRAINT fk_screening_seat_seat FOREIGN KEY (seat_id) REFERENCES seat (id) ON DELETE RESTRICT,
    CONSTRAINT fk_screening_seat_screening FOREIGN KEY (screening_id) REFERENCES screening (id) ON DELETE RESTRICT,
    CONSTRAINT fk_screening_seat_current_booking FOREIGN KEY (current_booking_id) REFERENCES booking (id) ON DELETE RESTRICT,
    CONSTRAINT chk_screening_seat_status CHECK (status IN ('AVAILABLE', 'HELD', 'SOLD')),
    CONSTRAINT chk_screening_seat_booking_consistency CHECK (
        (status = 'AVAILABLE' AND current_booking_id IS NULL) OR
        (status IN ('HELD', 'SOLD') AND current_booking_id IS NOT NULL))
);


CREATE TABLE booking_item (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    tariff_id INT NOT NULL,
    screening_seat_id BIGINT NOT NULL,
    booking_id BIGINT NOT NULL,
    final_price NUMERIC(12, 2) NOT NULL,
    applied_discount_percent SMALLINT NOT NULL,

    CONSTRAINT pk_booking_item PRIMARY KEY (id),
    CONSTRAINT uq_booking_item_booking_screening_seat UNIQUE (booking_id, screening_seat_id),
    CONSTRAINT fk_booking_item_tariff FOREIGN KEY (tariff_id) REFERENCES tariff(id) ON DELETE RESTRICT,
    CONSTRAINT fk_booking_item_screening_seat FOREIGN KEY (screening_seat_id) REFERENCES screening_seat (id) ON DELETE RESTRICT,
    CONSTRAINT fk_booking_item_booking FOREIGN KEY (booking_id) REFERENCES booking (id) ON DELETE RESTRICT,
    CONSTRAINT chk_booking_item_applied_discount_percent CHECK (applied_discount_percent >= 0 AND applied_discount_percent <= 100),
    CONSTRAINT chk_booking_item_final_price CHECK (final_price >= 0)
);


CREATE TABLE payment_attempt (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    booking_id BIGINT NOT NULL,
    status VARCHAR(30) NOT NULL,
    amount NUMERIC(12, 2) NOT NULL,
    idempotency_key VARCHAR(255) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    processed_at TIMESTAMPTZ,

    CONSTRAINT pk_payment_attempt PRIMARY KEY (id),
    CONSTRAINT uq_payment_attempt_booking_idempotency UNIQUE (booking_id, idempotency_key),
    CONSTRAINT fk_payment_attempt_booking FOREIGN KEY (booking_id) REFERENCES booking (id) ON DELETE RESTRICT,
    CONSTRAINT chk_payment_attempt_dates CHECK (processed_at IS NULL OR processed_at >= created_at),
    CONSTRAINT chk_payment_attempt_amount CHECK (amount >= 0),
    CONSTRAINT chk_payment_attempt_status CHECK (status IN ('PENDING', 'SUCCESS', 'FAILED')),
    CONSTRAINT chk_payment_attempt_processed_at CHECK (
            (status = 'PENDING' AND processed_at IS NULL) OR
            (status IN ('SUCCESS', 'FAILED') AND processed_at IS NOT NULL))
);


CREATE TABLE ticket (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    booking_item_id BIGINT NOT NULL,
    status VARCHAR(30) NOT NULL,
    ticket_code UUID NOT NULL,
    issued_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    returned_at TIMESTAMPTZ,

    CONSTRAINT pk_ticket PRIMARY KEY (id),
    CONSTRAINT uq_ticket_ticket_code UNIQUE (ticket_code),
    CONSTRAINT uq_ticket_booking_item UNIQUE (booking_item_id),
    CONSTRAINT fk_ticket_booking_item FOREIGN KEY (booking_item_id) REFERENCES booking_item (id) ON DELETE RESTRICT,
    CONSTRAINT chk_ticket_dates CHECK (returned_at IS NULL OR returned_at >= issued_at),
    CONSTRAINT chk_ticket_status CHECK (status IN ('ACTIVE', 'RETURNED')),
    CONSTRAINT chk_ticket_returned_at CHECK (
        (status = 'ACTIVE' AND returned_at IS NULL) OR
        (status IN ('RETURNED') AND returned_at IS NOT NULL))
);

-- hall indexes
CREATE INDEX idx_hall_hall_type ON hall (hall_type_id);

-- screening indexes
CREATE INDEX idx_screening_movie_advertising_start_time ON screening (movie_id, advertising_start_time);
CREATE INDEX idx_screening_hall_advertising_start_time ON screening (hall_id, advertising_start_time);

-- booking indexes
CREATE INDEX idx_booking_user_created_at ON booking (user_id, created_at DESC);
CREATE INDEX idx_booking_screening ON booking (screening_id);

-- screening seat indexes
CREATE INDEX idx_screening_seat_seat ON screening_seat (seat_id);
CREATE INDEX idx_screening_seat_current_booking ON screening_seat (current_booking_id) WHERE current_booking_id IS NOT NULL;
CREATE INDEX idx_screening_seat_screening_status ON screening_seat (screening_id, status);

-- booking item indexes
CREATE INDEX idx_booking_item_screening_seat ON booking_item (screening_seat_id);

-- payment attempt indexes
CREATE UNIQUE INDEX uq_payment_attempt_one_success_per_booking ON payment_attempt (booking_id) WHERE status = 'SUCCESS';